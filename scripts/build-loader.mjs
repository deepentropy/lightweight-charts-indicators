// Writes src/indicator-modules.ts: for each registry entry of src/index.ts whose calculate is `<module>.calculate`,
// the import of its module (the loader, src/loader.ts, imports only the module of the study it is asked for).
// Run: node scripts/build-loader.mjs (the tests check the file is up to date).
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../src/index.ts', import.meta.url), 'utf8');
const modules = new Map([...src.matchAll(/^import \* as (\w+) from '(\.\/[^']+)';/gm)].map((m) => [m[1], m[2]]));
const out = [];
let id = null;
for (const line of src.split('\n')) {
  const entry = line.match(/^ {4}id: '([^']+)',/);
  if (entry) {
    id = entry[1];
    continue;
  }
  const calc = line.match(/^ {4}calculate: (\w+)\.calculate,?$/);
  if (calc && id) {
    const path = modules.get(calc[1]);
    if (!path) throw new Error(`build-loader: no import for ${calc[1]} (${id})`);
    out.push(`  '${id}': () => import('${path}'),`);
    id = null;
  }
}

writeFileSync(
  new URL('../src/indicator-modules.ts', import.meta.url),
  `// Generated by scripts/build-loader.mjs from src/index.ts: do not edit.\n` +
    `/* eslint-disable */\n\n` +
    `/** The module of each study whose calculate is its module's, by registry id. */\n` +
    `export const INDICATOR_MODULES: Record<string, () => Promise<unknown>> = {\n${out.join('\n')}\n};\n`,
);
console.log(`indicator-modules.ts: ${out.length} studies`);
